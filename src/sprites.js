export function bmpWidth(bmp) {
  return bmp[0].length;
}

export function bmpHeight(bmp) {
  return bmp.length;
}

/* Pre-rendered sprite cache: (bitmap, color) -> offscreen canvas. */
const cache = new Map();

function renderBmp(bmp, color) {
  const c = document.createElement('canvas');
  c.width = bmpWidth(bmp);
  c.height = bmpHeight(bmp);
  const g = c.getContext('2d');
  g.fillStyle = color;
  for (let y = 0; y < bmp.length; y++) {
    const row = bmp[y];
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '1') g.fillRect(x, y, 1, 1);
    }
  }
  return c;
}

export function drawSprite(ctx, bmp, x, y, color) {
  let byColor = cache.get(bmp);
  if (!byColor) {
    byColor = new Map();
    cache.set(bmp, byColor);
  }
  let img = byColor.get(color);
  if (!img) {
    img = renderBmp(bmp, color);
    byColor.set(color, img);
  }
  ctx.drawImage(img, Math.round(x), Math.round(y));
}

