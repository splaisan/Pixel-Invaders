export const FONT_W = 5;
export const FONT_H = 7;
export const FONT_ADVANCE = 6;

export function textWidth(text, scale = 1) {
  return (text.length * FONT_ADVANCE - 1) * scale;
}

export function drawText(ctx, text, x, y, color, scale = 1) {
  const upper = String(text).toUpperCase();
  let cx = Math.round(x);
  for (const ch of upper) {
    const glyph = FONT[ch] || FONT['?'];
    for (let gy = 0; gy < FONT_H; gy++) {
      const row = glyph[gy];
      for (let gx = 0; gx < FONT_W; gx++) {
        if (row[gx] === '1') {
          ctx.fillStyle = color;
          ctx.fillRect(cx + gx * scale, Math.round(y) + gy * scale, scale, scale);
        }
      }
    }
    cx += FONT_ADVANCE * scale;
  }
}

export function drawTextCentered(ctx, text, centerX, y, color, scale = 1) {
  drawText(ctx, text, centerX - textWidth(text, scale) / 2, y, color, scale);
}

/* Bunker shape generator: rounded-top arch block with a bottom notch,
   returned as a mutable Uint8Array grid (1 = solid pixel). */
export function makeBunkerGrid(w, h) {
  const grid = new Uint8Array(w * h);
  grid.fill(1);
  // slope the two top corners
  for (let r = 0; r < 4; r++) {
    for (let c = 0; c < 4 - r; c++) {
      grid[r * w + c] = 0;
      grid[r * w + (w - 1 - c)] = 0;
    }
  }
  // carve the bottom-center arch
  const cx0 = Math.floor(w / 2) - 3;
  const cx1 = Math.floor(w / 2) + 2;
  for (let r = h - 4; r < h; r++) {
    for (let c = cx0; c <= cx1; c++) grid[r * w + c] = 0;
  }
  for (let c = cx0 + 1; c <= cx1 - 1; c++) grid[(h - 5) * w + c] = 0;
  return grid;
}
